export function generateSeedData() {
  console.log('Generating seed dataset...')

  const allDocuments = []

  // Add Categories
  for (const cat of categories) {
    allDocuments.push(cat)
  }

  // Add Instructors
  for (const inst of instructors) {
    allDocuments.push(inst)
  }

  let totalLessons = 0
  let totalModules = 0

  // Add Courses, Modules, and Lessons
  for (const course of coursesData) {
    const courseDocId = `course.${course.slug}`
    const modulesArray = []

    for (let mIdx = 0; mIdx < course.modules.length; mIdx++) {
      const mod = course.modules[mIdx]
      totalModules++
      const moduleKey = `${course.slug}-module-${mIdx + 1}`
      const lessonRefs = []

      for (let lIdx = 0; lIdx < mod.lessons.length; lIdx++) {
        const lesson = mod.lessons[lIdx]
        totalLessons++
        const lessonDocId = `lesson.${course.slug}-${lesson.slug}`

        const lessonDoc = {
          _id: lessonDocId,
          _type: 'lesson',
          title: lesson.title,
          slug: { _type: 'slug', current: `${course.slug}-${lesson.slug}` },
          videoUrl: `https://www.youtube.com/watch?v=${lesson.youtubeId}`,
          thumbnail: {
            _type: 'image',
            _sanityAsset: `image@https://i.ytimg.com/vi/${lesson.youtubeId}/hqdefault.jpg`,
            alt: `Video thumbnail for ${lesson.title}`,
          },
          duration: lesson.duration,
          freePreview: mIdx === 0 && lIdx === 0, // Free preview on first lesson of each course
          studentCount: Math.max(800, Math.floor(course.studentCount * (1 - (mIdx * 3 + lIdx) * 0.05))),
          notes: createPortableTextNotes(
            course.title,
            mod.title,
            lesson.title,
            lesson.summary,
            lesson.points
          ),
          keyPoints: lesson.points,
          proTip: lesson.proTip,
          resources: (lesson.resources || []).map((res, rIdx) => ({
            _type: 'resource',
            _key: `${course.slug}-${lesson.slug}-res-${rIdx}`,
            type: res.type || 'link',
            title: res.title,
            description: res.description,
            url: res.url,
          })),
        }

        allDocuments.push(lessonDoc)

        lessonRefs.push({
          _type: 'reference',
          _key: `${course.slug}-${lesson.slug}-ref`,
          _ref: lessonDocId,
        })
      }

      modulesArray.push({
        _type: 'module',
        _key: moduleKey,
        title: mod.title,
        summary: mod.summary,
        lessons: lessonRefs,
      })
    }

    const courseDoc = {
      _id: courseDocId,
      _type: 'course',
      title: course.title,
      slug: { _type: 'slug', current: course.slug },
      summary: course.summary,
      coverImage: {
        _type: 'image',
        _sanityAsset: `image@https://picsum.photos/seed/vertex-course-${course.slug}/1600/900`,
        alt: `Cover image for ${course.title}`,
      },
      instructor: {
        _type: 'reference',
        _ref: course.instructorRef,
      },
      category: {
        _type: 'reference',
        _ref: course.categoryRef,
      },
      level: course.level,
      price: course.price,
      popular: course.popular,
      studentCount: course.studentCount,
      learningOutcomes: course.learningOutcomes.map((outcome, oIdx) => ({
        _type: 'learningOutcome',
        _key: `${course.slug}-outcome-${oIdx}`,
        icon: outcome.icon,
        title: outcome.title,
        description: outcome.description,
      })),
      modules: modulesArray,
    }

    allDocuments.push(courseDoc)
  }

  // Non-destructive merge: Load existing seed.ndjson if it exists
  const existingMap = new Map()
  if (fs.existsSync(seedFilePath)) {
    const existingRaw = fs.readFileSync(seedFilePath, 'utf-8')
    const existingLines = existingRaw.trim().split('\n').filter(Boolean)
    for (const line of existingLines) {
      try {
        const doc = JSON.parse(line)
        if (doc && doc._id) {
          existingMap.set(doc._id, doc)
        }
      } catch {
        // ignore invalid lines
      }
    }
  }

  // Merge newly generated documents into the existing collection
  for (const doc of allDocuments) {
    existingMap.set(doc._id, doc)
  }

  const finalMergedDocs = Array.from(existingMap.values())

  // Format into NDJSON
  const ndjson = finalMergedDocs.map((doc) => JSON.stringify(doc)).join('\n') + '\n'
  fs.writeFileSync(seedFilePath, ndjson, 'utf-8')

  console.log(`\nGenerated seed dataset successfully (Merged Non-Destructively)!`)
  console.log(`Newly generated items in this batch: ${allDocuments.length}`)
  console.log(`Total preserved documents in seed.ndjson: ${finalMergedDocs.length}`)
  console.log(`Saved to: ${seedFilePath}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateSeedData()
}
