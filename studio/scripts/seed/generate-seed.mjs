// Helper for Portable Text Notes
function createPortableTextNotes(courseTitle, moduleTitle, lessonTitle, summaryText, points) {
  const bulletBlocks = points.map((p, idx) => ({
    _type: 'block',
    _key: `point-${idx}`,
    style: 'normal',
    listItem: 'bullet',
    level: 1,
    markDefs: [],
    children: [
      {
        _type: 'span',
        _key: `point-${idx}-span`,
        text: p,
        marks: [],
      },
    ],
  }))

  return [
    {
      _type: 'block',
      _key: 'intro',
      style: 'normal',
      markDefs: [],
      children: [
        {
          _type: 'span',
          _key: 'intro-span',
          text: summaryText,
          marks: [],
        },
      ],
    },
    {
      _type: 'block',
      _key: 'h2-covers',
      style: 'h2',
      markDefs: [],
      children: [
        {
          _type: 'span',
          _key: 'h2-covers-span',
          text: 'What this lesson covers',
          marks: [],
        },
      ],
    },
    ...bulletBlocks,
    {
      _type: 'block',
      _key: 'outro',
      style: 'normal',
      markDefs: [],
      children: [
        {
          _type: 'span',
          _key: 'outro-span',
          text: `This lesson is part of ${moduleTitle} in ${courseTitle}. It provides foundational principles followed by practical code demonstrations.`,
          marks: [],
        },
      ],
    },
  ]
}

// Helper for Instructor Bio
function createBioBlocks(slug, paragraphs) {
  return paragraphs.map((text, idx) => ({
    _type: 'block',
    _key: `${slug}-bio-${idx}`,
    style: 'normal',
    markDefs: [],
    children: [
      {
        _type: 'span',
        _key: `${slug}-bio-${idx}-span`,
        text,
        marks: [],
      },
    ],
  }))
}

